    private static GenUiTemplateDefinition Foundation(
        string key,
        string name,
        string description,
        string category,
        IReadOnlyList<string> tags,
        string implementation,
        GenUiTemplateScale scale,
        IReadOnlyList<string> apps,
        IReadOnlyList<string> inputs,
        IReadOnlyList<string> outputs,
        IReadOnlyList<GenUiEventType> events,
        IReadOnlyList<string> primitives,
        IReadOnlyList<string>? services = null,
        IReadOnlyList<string>? capabilities = null,
        bool network = false,
        bool offline = true,
        bool deterministic = false,
        GenUiAgentInteractionMode agent = GenUiAgentInteractionMode.Optional,
        GenUiStateOwnership ownership = GenUiStateOwnership.Thread,
        GenUiTemplateMaturity maturity = GenUiTemplateMaturity.Foundation) => new(
        GuidUtility.FromStableName("haven.template." + key), key, "1.0.0", name, description, category, tags,
        implementation, scale, apps, apps, inputs, outputs, events,
        ["title", "accent", "layout", "emptyState"],
        ["Stable typed input matching the declared template contract."],
        events.Select(item => item.ToString()).ToArray(),
        primitives, services ?? [], capabilities ?? [],
        deterministic ? [] : [ToolCapability.Text, ToolCapability.StructuredOutput],
        network, offline, CapabilityPlatform.All,
        "Keyboard reachable, labelled controls, focus order, scalable text, high-contrast tokens, and non-visual status alternatives are required.",
        SupportsPersistence: true, SupportsThreadScope: true, SupportsUserApps: true,
        SupportsMiniApps: scale is GenUiTemplateScale.Primitive or GenUiTemplateScale.Pattern,
        SupportsEmbedding: true, agent, deterministic, ownership, maturity,
        IsBuiltIn: true, IsEnabled: true, UpdatedAt: DateTimeOffset.UnixEpoch);
